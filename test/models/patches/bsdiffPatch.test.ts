import BSDiffPatch from '../../../src/models/patches/bsdiffPatch.js';
import { applyPatch, INPUT16, parsePatch } from './patchTestUtil.js';

const patchFrom = BSDiffPatch.patchFrom.bind(BSDiffPatch);
const FILE_NAME = 'patch 00000000.bdf';
// "BSDIFF40", then 8-byte sign-magnitude LE control block length, diff block length, and new
// size, then the bzip2-compressed control, diff, and extra blocks. Each control record is a
// diff length, extra length, and seek length.
// [diff 16, extra 4, seek 0], a zeroed diff, and the extra bytes "aabbccdd"
const GROW =
  '42534449464634302b0000000000000025000000000000001400000000000000425a6839314159265359c7b1cf66000005e0004c08400020002186819a0c56c9b8bb9229c284863d8e7b30425a6839314159265359aad2dd3700000040004004200021008283177245385090aad2dd37425a6839314159265359db91780f000000001e00100008000400022000219a68334d133c5dc914e142436e45e03c';

describe('patchFrom', () => {
  it('should parse', async () => {
    await expect(parsePatch(patchFrom, FILE_NAME, GROW)).resolves.toEqual({
      crcBefore: '00000000',
      crcAfter: undefined,
      sizeAfter: 20,
    });
  });

  test.each([
    ['empty', ''],
    ['short header', GROW.slice(0, 62)],
    ['wrong magic', `4253444946463431${GROW.slice(16)}`],
    ['negative control block length', `${GROW.slice(0, 30)}80${GROW.slice(32)}`],
    ['negative new size', `${GROW.slice(0, 62)}80${GROW.slice(64)}`],
    ['blocks past the end', `${GROW.slice(0, 16)}ffffff0000000000${GROW.slice(32)}`],
  ])('should throw on %s', async (_name, patchHex) => {
    await expect(parsePatch(patchFrom, FILE_NAME, patchHex)).rejects.toThrow(
      /BSDiff patch header is invalid/,
    );
  });
});

